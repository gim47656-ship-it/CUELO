const ANSWER_STATUS_MESSAGES: Record<string, Record<string, string>> = { ko, en, "zh-CN": zhCN };

export type AnswerStatusTranslate = (key: AnswerStatusMessageKey, params?: TranslationParams) => string;

/** 이 기능의 문구 조회. 앱 locale을 따르고, 없는 언어는 공용 규칙대로 영어로 떨어진다. */
export function useAnswerStatusText(): { st: AnswerStatusTranslate; locale: Locale } {
  const { locale } = useI18n();
  const st = useCallback<AnswerStatusTranslate>(
    (key, params) => translateMessage(locale, key, ANSWER_STATUS_MESSAGES, params),
    [locale],
  );
  return { st, locale };
}
