const LOUNGE_MESSAGES: Record<string, Record<string, string>> = { ko, en, "zh-CN": zhCN };

export type LoungeTranslate = (key: LoungeMessageKey, params?: TranslationParams) => string;

/** 단톡방 문구 조회. 앱 locale을 그대로 따르고, 없는 언어는 공용 규칙대로 영어로 떨어진다. */
export function useLoungeText(): { lt: LoungeTranslate; locale: Locale } {
  const { locale } = useI18n();
  const lt = useCallback<LoungeTranslate>(
    (key, params) => translateMessage(locale, key, LOUNGE_MESSAGES, params),
    [locale],
  );
  return { lt, locale };
}

/**
 * roster alias(`"YUKI(유키)"`)에서 화면 이름을 꺼낸다. 한국어 화면은 괄호 안 이름, 그 밖은 영문
 * 이름이다. 백엔드는 두 표기 모두를 멘션으로 알아듣는다.
 */
export function loungeMemberName(alias: string, locale: string): string {
  const match = /^([^(]+)\(([^)]+)\)$/.exec(alias.trim());
  if (!match) return alias;
  return locale === "ko" ? match[2] : match[1];
}
